@router.post("/{lead_id}/create-listing")
async def create_listing_from_lead(
    lead_id: str,
    request: CreateListingFromLeadRequest,
    current_user: dict = Depends(get_current_user)
):
    """Create a property listing from a lead"""
    if current_user["role"] not in [UserRole.SUPERUSER, UserRole.ADMIN]:
        raise HTTPException(status_code=403, detail="Admin access required")
    
    lead = await db.property_leads.find_one({"id": lead_id}, {"_id": 0})
    if not lead:
        raise HTTPException(status_code=404, detail="Property lead not found")
    
    # Check if listing already exists
    if lead.get("listing_id"):
        existing = await db.properties.find_one({"id": lead["listing_id"]}, {"_id": 0})
        if existing:
            return {
                "message": "Listing already exists for this lead",
                "listing": existing,
                "listing_id": lead["listing_id"]
            }
    
    now = datetime.now(timezone.utc).isoformat()
    listing_id = str(uuid.uuid4())
    
    # Create listing from lead data
    listing = {
        "id": listing_id,
        "title": f"{lead.get('address', 'Property')}",
        "address": lead.get("address", ""),
        "city": lead.get("city", ""),
        "state": lead.get("state", "FL"),
        "zip_code": lead.get("zip_code", ""),
        "county": lead.get("county", ""),
        "price": lead.get("estimated_value", 0),
        "property_type": lead.get("property_type", "single_family"),
        "bedrooms": lead.get("bedrooms"),
        "bathrooms": lead.get("bathrooms"),
        "sqft": lead.get("sqft"),
        "square_feet": lead.get("sqft"),  # Legacy field
        "lot_size": lead.get("lot_size"),
        "year_built": lead.get("year_built"),
        "description": request.custom_description or f"Beautiful property located at {lead.get('address', '')} in {lead.get('city', '')}.",
        "features": [],
        "images": [],
        "status": "active",
        "mls_number": "",
        "source": "property_lead",
        "source_lead_id": lead_id,
        "created_at": now,
        "updated_at": now
    }
    
    await db.properties.insert_one(listing)
    
    # Update lead with listing reference
    await db.property_leads.update_one(
        {"id": lead_id},
        {
            "$set": {"listing_id": listing_id, "updated_at": now},
            "$push": {"activity": {
                "type": "listing_created",
                "description": f"Listing created from lead by {current_user['name']}",
                "user": current_user["name"],
                "timestamp": now,
                "data": {"listing_id": listing_id}
            }}
        }
    )
    
    result = {
        "message": "Listing created successfully",
        "listing_id": listing_id,
        "listing": listing
    }
    
    # Optionally create landing page
    if request.create_landing_page:
        import re
        
        # Generate slug
        full_address = f"{listing['address']} {listing['city']} {listing['state']}"
        slug = re.sub(r'[^a-z0-9\s-]', '', full_address.lower())
        slug = re.sub(r'[\s]+', '-', slug)
        slug = re.sub(r'-+', '-', slug).strip('-')
        
        # Ensure unique slug
        slug_exists = await db.landing_pages.find_one({"slug": slug})
        if slug_exists:
            slug = f"{slug}-{str(uuid.uuid4())[:8]}"
        
        # Get agent info
        settings = await db.settings.find_one({"type": "agent"}, {"_id": 0})
        
        landing_page_id = str(uuid.uuid4())
        
        landing_page = {
            "id": landing_page_id,
            "listing_id": listing_id,
            "slug": slug,
            "custom_headline": request.custom_headline or listing["title"],
            "custom_description": listing["description"],
            "videos": [],
            "additional_images": [],
            "virtual_tour_url": "",
            "show_map": True,
            "show_contact_form": True,
            "agent_name": settings.get("agent_name", "") if settings else "",
            "agent_phone": settings.get("agent_phone", "") if settings else "",
            "agent_email": settings.get("agent_email", "") if settings else "",
            "agent_photo": settings.get("agent_photo", "") if settings else "",
            "theme": request.theme,
            "status": "draft",
            "preview_url": build_landing_page_url(slug),
            "created_at": now,
            "updated_at": now
        }
        
        await db.landing_pages.insert_one(landing_page)
        
        # Update lead with landing page reference
        await db.property_leads.update_one(
            {"id": lead_id},
            {
                "$set": {
                    "landing_page_id": landing_page_id,
                    "landing_page_url": build_landing_page_url(landing_page["slug"])
                },
                "$push": {"activity": {
                    "type": "landing_page_created",
                    "description": f"Landing page created by {current_user['name']}",
                    "user": current_user["name"],
                    "timestamp": now,
                    "data": {
                        "landing_page_id": landing_page_id,
                        "slug": slug
                    }
                }}
            }
        )
        
        result["landing_page_id"] = landing_page_id
        result["landing_page_url"] = build_landing_page_url(landing_page["slug"])
        result["landing_page"] = landing_page
    
    return result


