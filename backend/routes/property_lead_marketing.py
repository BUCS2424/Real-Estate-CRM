@router.post("/{lead_id}/brochure/generate")
async def generate_brochure_endpoint(
    lead_id: str,
    request: BrochureRequest,
    current_user: dict = Depends(get_current_user)
):
    """Generate a brochure PDF for download"""
    if current_user["role"] not in [UserRole.SUPERUSER, UserRole.ADMIN]:
        raise HTTPException(status_code=403, detail="Admin access required")
    
    # Get lead data
    lead = await db.property_leads.find_one({"id": lead_id}, {"_id": 0})
    if not lead:
        raise HTTPException(status_code=404, detail="Property lead not found")
    
    # Get agent info from settings or current user
    settings = await db.settings.find_one({"type": "agent"}, {"_id": 0})
    agent_info = {
        "name": settings.get("agent_name", current_user.get("name", "Agent")) if settings else current_user.get("name", "Agent"),
        "phone": settings.get("agent_phone", "") if settings else "",
        "email": settings.get("agent_email", current_user.get("email", "")) if settings else current_user.get("email", ""),
        "title": settings.get("agent_title", "Real Estate Specialist") if settings else "Real Estate Specialist"
    }
    
    # Get branding
    branding = await db.settings.find_one({"type": "branding"}, {"_id": 0})
    
    # Check for landing page URL
    landing_page_url = None
    if request.include_qr and lead.get("landing_page_id"):
        landing_page = await db.landing_pages.find_one({"id": lead["landing_page_id"]}, {"_id": 0})
        if landing_page:
            landing_page_url = build_landing_page_url(landing_page["slug"])
    
    # Generate brochure based on template type
    if request.template == 'foldable':
        # Generate 2-page foldable brochure
        pdf_buffer = await generate_foldable_brochure(
            lead=lead,
            agent_info=agent_info,
            branding=branding,
            landing_page_url=landing_page_url,
            property_images=request.property_images or lead.get('images', [])
        )
        address_slug = lead.get('address', 'property').lower().replace(' ', '-')[:30]
        filename = f"brochure-{address_slug}-foldable.pdf"
    else:
        # Generate standard brochure
        pdf_buffer, filename = await generate_brochure(
            lead=lead,
            agent_info=agent_info,
            template=request.template,
            landing_page_url=landing_page_url
        )
    
    # Log activity
    activity_entry = {
        "type": "brochure_generated",
        "description": f"Brochure ({request.template}) generated by {current_user['name']}",
        "user": current_user["name"],
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "data": {"template": request.template}
    }
    
    await db.property_leads.update_one(
        {"id": lead_id},
        {"$push": {"activity": activity_entry}}
    )
    
    return StreamingResponse(
        pdf_buffer,
        media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )


