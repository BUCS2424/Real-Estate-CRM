def get_site_url() -> str:
    site_url = os.environ.get("SITE_URL")
    if not site_url:
        raise HTTPException(status_code=500, detail="SITE_URL is not configured")
    return site_url.rstrip("/")


def build_landing_page_url(slug: str) -> str:
    return f"{get_site_url()}/landing/{slug}"

router = APIRouter()


class BrochureRequest(BaseModel):
    template: str = 'flyer'  # flyer, postcard, trifold, foldable
    include_qr: bool = True
    property_images: Optional[List[str]] = None


class EmailBrochureRequest(BaseModel):
    template: str = 'flyer'
    recipient_email: str
    subject: Optional[str] = None
    message: Optional[str] = None
    include_landing_page_link: bool = True


class CreateListingFromLeadRequest(BaseModel):
    create_landing_page: bool = True
    theme: str = 'luxury'
    custom_headline: Optional[str] = None
    custom_description: Optional[str] = None


