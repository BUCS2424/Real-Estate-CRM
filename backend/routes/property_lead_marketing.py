@router.post("/{lead_id}/brochure/email")
async def email_brochure(
    lead_id: str,
    request: EmailBrochureRequest,
    background_tasks: BackgroundTasks,
    current_user: dict = Depends(get_current_user)
):
    """Email the brochure to the property owner"""
    if current_user["role"] not in [UserRole.SUPERUSER, UserRole.ADMIN]:
        raise HTTPException(status_code=403, detail="Admin access required")
    
    lead = await db.property_leads.find_one({"id": lead_id}, {"_id": 0})
    if not lead:
        raise HTTPException(status_code=404, detail="Property lead not found")
    
    # Get SMTP settings
    smtp_settings = await db.settings.find_one({"type": "smtp"}, {"_id": 0})
    if not smtp_settings or not smtp_settings.get("host"):
        raise HTTPException(status_code=400, detail="SMTP not configured. Please configure email settings first.")
    
    # Get agent info
    settings = await db.settings.find_one({"type": "agent"}, {"_id": 0})
    agent_info = {
        "name": settings.get("agent_name", current_user.get("name", "Agent")) if settings else current_user.get("name", "Agent"),
        "phone": settings.get("agent_phone", "") if settings else "",
        "email": settings.get("agent_email", current_user.get("email", "")) if settings else current_user.get("email", ""),
        "title": settings.get("agent_title", "Real Estate Specialist") if settings else "Real Estate Specialist"
    }
    
    # Get landing page URL if available
    landing_page_url = None
    if request.include_landing_page_link and lead.get("landing_page_id"):
        landing_page = await db.landing_pages.find_one({"id": lead["landing_page_id"]}, {"_id": 0})
        if landing_page:
            landing_page_url = build_landing_page_url(landing_page["slug"])
    
    # Generate brochure
    pdf_buffer, filename = await generate_brochure(
        lead=lead,
        agent_info=agent_info,
        template=request.template,
        landing_page_url=landing_page_url
    )
    
    # Prepare email
    owner_name = lead.get("owner_name", "Homeowner")
    address = lead.get("address", "your property")
    
    subject = request.subject or f"Exclusive Market Analysis for {address}"
    
    default_message = f"""
Dear {owner_name},

I hope this message finds you well. I wanted to reach out regarding your property at {address}.

After analyzing the current market conditions in {lead.get('city', 'your area')}, I believe there may be an excellent opportunity to discuss your property's potential.

I've prepared a personalized brochure with details about your property and current market insights. Please find it attached to this email.

{f'You can also view more information online at: {landing_page_url}' if landing_page_url else ''}

I would love to schedule a brief, no-obligation conversation to discuss how I can help you maximize the value of your property.

Please feel free to reach out at your convenience.

Best regards,
{agent_info['name']}
{agent_info['title']}
{agent_info['phone']}
{agent_info['email']}

Hidden Haven Realty
"""
    
    message_body = request.message or default_message
    
    # Send email in background
    async def send_email_task():
        try:
            msg = MIMEMultipart()
            msg['Subject'] = subject
            msg['From'] = smtp_settings.get('from_email', agent_info['email'])
            msg['To'] = request.recipient_email
            
            # Add HTML body
            html_body = f"""
            <html>
            <body style="font-family: Arial, sans-serif; line-height: 1.6; color: #0a1628;">
            {message_body.replace(chr(10), '<br/>')}
            </body>
            </html>
            """
            msg.attach(MIMEText(html_body, 'html'))
            
            # Attach PDF
            pdf_attachment = MIMEApplication(pdf_buffer.read(), _subtype='pdf')
            pdf_attachment.add_header('Content-Disposition', 'attachment', filename=filename)
            msg.attach(pdf_attachment)
            
            # Send via SMTP
            with smtplib.SMTP(smtp_settings['host'], smtp_settings.get('port', 587)) as server:
                if smtp_settings.get('use_tls', True):
                    server.starttls()
                if smtp_settings.get('username') and smtp_settings.get('password'):
                    server.login(smtp_settings['username'], smtp_settings['password'])
                server.send_message(msg)
            
            # Log success
            await db.property_leads.update_one(
                {"id": lead_id},
                {"$push": {"activity": {
                    "type": "brochure_emailed",
                    "description": f"Brochure emailed to {request.recipient_email} by {current_user['name']}",
                    "user": current_user["name"],
                    "timestamp": datetime.now(timezone.utc).isoformat(),
                    "data": {
                        "recipient": request.recipient_email,
                        "template": request.template,
                        "landing_page_url": landing_page_url
                    }
                }}}
            )
            
        except Exception as e:
            print(f"Email send error: {e}")
            # Log failure
            await db.property_leads.update_one(
                {"id": lead_id},
                {"$push": {"activity": {
                    "type": "email_failed",
                    "description": f"Failed to email brochure: {str(e)}",
                    "user": current_user["name"],
                    "timestamp": datetime.now(timezone.utc).isoformat()
                }}}
            )
    
    background_tasks.add_task(send_email_task)
    
    return {
        "message": f"Email queued for delivery to {request.recipient_email}",
        "recipient": request.recipient_email,
        "template": request.template,
        "landing_page_url": landing_page_url
    }


